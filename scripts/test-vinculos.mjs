import assert from "node:assert/strict";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { MemoryRouter } from "react-router";
import { createServer } from "vite";
const server = await createServer({ server: { middlewareMode: true }, appType: "custom" });
try {
  const { cursosInstitucionais, normalizarCurso, areasEquipe, atuacoesDocentes, atuacaoBncc, professorAtuaNoCurso } = await server.ssrLoadModule("/src/config/profissionais.ts");
  const { default: Curso } = await server.ssrLoadModule("/src/components/common/ProfessionalCoursesField.tsx");
  const { default: Registrar } = await server.ssrLoadModule("/src/pages/auth/RegisterPage.tsx");
  const { AuthContext } = await server.ssrLoadModule("/src/contexts/AuthContext.ts");
  assert.equal(cursosInstitucionais.length, 5);
  assert.equal(normalizarCurso("Análise e desenvolvimento de Sistemas"), cursosInstitucionais[3]);
  assert.equal(normalizarCurso("Computação"), "Computação", "Um curso antigo não deve ser convertido por suposição");
  assert.ok(areasEquipe.includes("Tradução e interpretação de Libras"));
  const curso = renderToStaticMarkup(React.createElement(Curso, { value: [cursosInstitucionais[0], cursosInstitucionais[3]], onChange() {} }));
  assert.match(curso, /aria-expanded="false"/);
  assert.equal((curso.match(/role="checkbox"/g) ?? []).length, atuacoesDocentes.length);
  assert.equal((curso.match(/aria-checked="true"/g) ?? []).length, 2, "ADS e Informática podem estar selecionados ao mesmo tempo");
  assert.match(curso, /BNCC/);
  assert.ok(cursosInstitucionais.slice(0, 3).every(c => professorAtuaNoCurso([atuacaoBncc], c)));
  assert.equal(professorAtuaNoCurso([atuacaoBncc], cursosInstitucionais[3]), false);
  assert.equal(professorAtuaNoCurso([atuacaoBncc], cursosInstitucionais[4]), false);
  const cadastro = renderToStaticMarkup(React.createElement(MemoryRouter, null, React.createElement(AuthContext.Provider, { value: { usuario: null, register: async () => ({}), login: async () => ({}), logout() {}, atualizarDadosPerfil() {} } }, React.createElement(Registrar))));
  const disciplina = cadastro.match(/<input[^>]*name="disciplina"[^>]*>/)?.[0];
  assert.equal(disciplina, undefined, "A disciplina será preenchida depois do cadastro");
  assert.match(cadastro, /Selecionar cursos e áreas de atuação/);
  const { vinculosEstudanteService } = await server.ssrLoadModule("/src/services/vinculosEstudanteService.ts");
  const { http } = await server.ssrLoadModule("/src/services/http.ts");
  const chamadas = [];
  http.defaults.adapter = async config => { chamadas.push(config); return { status: 200, statusText: "OK", headers: {}, config, data: [] }; };
  await vinculosEstudanteService.listar(4);
  await vinculosEstudanteService.candidatos(4);
  await vinculosEstudanteService.associar(4, 12, "Apoio educacional");
  await vinculosEstudanteService.encerrar(4, { id: 9, versao: 2 }, "Acompanhamento encerrado");
  assert.deepEqual(chamadas.map(c => [c.method, c.url]), [["get", "/estudantes/4/profissionais"], ["get", "/estudantes/4/profissionais/disponiveis"], ["post", "/estudantes/4/profissionais"], ["post", "/estudantes/4/profissionais/9/encerrar"]]);
  assert.deepEqual(JSON.parse(chamadas[2].data), { profissionalId: 12, motivo: "Apoio educacional" });
  assert.deepEqual(JSON.parse(chamadas[3].data), { versao: 2, motivo: "Acompanhamento encerrado" });
  assert.ok(chamadas.every(c => c.withCredentials));
  console.log("Vínculos: cursos, seleção do professor, disciplina opcional e operações autenticadas verificados.");
} finally { await server.close(); }
