import assert from "node:assert/strict";
import { createServer } from "vite";
const server = await createServer({ server: { middlewareMode: true }, appType: "custom" });
try {
  const { canAccess } = await server.ssrLoadModule("/src/config/access.ts");
  const { getMenuItems } = await server.ssrLoadModule("/src/components/layout/navigation/menu.ts");
  const { usuariosService } = await server.ssrLoadModule("/src/services/usuariosService.ts");
  const { http } = await server.ssrLoadModule("/src/services/http.ts");
  const { exigirAcessoRelatorios } = await server.ssrLoadModule("/src/services/relatorios/relatoriosService.ts");
  const pessoa = { id: 2, perfilId: 8, nome: "Pessoa Teste", email: "teste@example.invalid", perfil: "PROFESSOR", permissoes: ["usuarios"] };
  assert.equal(canAccess(pessoa, "usuarios"), true);
  assert.equal(canAccess(pessoa, "usuarios.gerenciar"), false);
  assert.equal(canAccess({ ...pessoa, perfil: "COORDENADOR", permissoes: [] }, "usuarios"), false, "Um bloqueio individual deve prevalecer sobre o perfil");
  const menu = getMenuItems(pessoa).find(item => item.label === "Administração");
  assert.deepEqual(menu.children.map(item => item.label), ["Usuários"]);
  assert.equal(menu.children[0].path, "/professor/administracao/usuarios");
  assert.equal(typeof menu.children[0].icon, "function");
  assert.equal(getMenuItems({ ...pessoa, permissoes: [] }).some(item => item.label === "Administração"), false);
  const menuProfessor = getMenuItems("PROFESSOR");
  assert.equal(menuProfessor.find(item => item.label === "Acompanhamento pedagógico")?.section, "Professores");
  assert.equal(menuProfessor.some(item => item.label === "Atendimentos"), false);
  assert.equal(menuProfessor.find(item => item.label === "Meus estudantes").children.some(item => item.path.endsWith("/adaptacoes")), false);
  assert.equal(getMenuItems("EQUIPE_MULTIDISCIPLINAR").find(item => item.label === "Atendimentos")?.section, "Equipe multidisciplinar");
  assert.equal(getMenuItems({ ...pessoa, permissoes: ["suporte.registrar"] }).find(item => item.label === "Atendimentos")?.section, "Equipe multidisciplinar", "Uma permissão extra deve aparecer na área correspondente sem trocar o perfil");
  assert.equal(getMenuItems({ ...pessoa, permissoes: [] }).some(item => item.section), false, "Áreas sem permissões devem permanecer ocultas");
  globalThis.sessionStorage = { getItem: () => JSON.stringify({ ...pessoa, permissoes: ["relatorios"] }) };
  assert.doesNotThrow(exigirAcessoRelatorios, "Uma permissão extra deve funcionar fora do perfil da coordenação");
  globalThis.sessionStorage.getItem = () => JSON.stringify({ ...pessoa, perfil: "COORDENADOR", permissoes: [] });
  assert.throws(exigirAcessoRelatorios);
  const chamadas = [];
  http.defaults.adapter = async config => { chamadas.push(config); return { status: 200, statusText: "OK", headers: {}, config, data: config.method === "get" ? [pessoa] : pessoa }; };
  assert.equal((await usuariosService.listar())[0].id, 2);
  await usuariosService.editar(2, { nome: "Nome atualizado", email: "novo@example.invalid" });
  await usuariosService.situacao(2, false);
  await usuariosService.permissoes(2, { usuarios: true });
  await usuariosService.excluir(2);
  assert.deepEqual(chamadas.map(c => [c.method, c.url]), [["get", "/usuarios"], ["put", "/usuarios/2"], ["patch", "/usuarios/2/situacao"], ["put", "/usuarios/2/permissoes"], ["delete", "/usuarios/2"]]);
  assert.ok(chamadas.every(c => c.withCredentials));
  assert.equal(JSON.parse(chamadas[2].data).ativo, false);
  assert.deepEqual(JSON.parse(chamadas[3].data), { ajustes: { usuarios: true } });
  console.log("Permissões: acesso extra, bloqueio do perfil, menu, ícones e operações autenticadas verificados.");
} finally { delete globalThis.sessionStorage; await server.close(); }
